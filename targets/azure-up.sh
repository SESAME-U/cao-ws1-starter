#!/usr/bin/env bash
# Workshop 1, Azure path: two Ubuntu VMs in one virtual network.
#
#   web1: public IP, ports 22 and 80 open
#   db1 : public IP for SSH only; MariaDB (3306) is reachable from inside the
#         virtual network only, so web1 talks to it on its private IP.
#
# Cost: two Standard_B1s VMs. Destroy them at the end with  make azure-down
# If Azure refuses the region, run again with e.g.  LOCATION=francecentral
set -euo pipefail
cd "$(dirname "$0")/.."

LOCATION="${LOCATION:-westeurope}"
OWNER="${GITHUB_USER:-$(whoami)}"
RG="${RG:-rg-cao-ws1-$OWNER}"
KEY="${KEY:-$HOME/.ssh/cao_lab}"
SIZE="${SIZE:-Standard_B1s}"
TAGS=(course=cao owner="$OWNER" lab=ws1)

az account show >/dev/null || { echo "Run 'az login --use-device-code' first."; exit 1; }
[[ -f "$KEY" ]] || ssh-keygen -q -t ed25519 -N "" -f "$KEY" -C "cao-lab"

echo "==> Resource group $RG and virtual network in $LOCATION"
az group create -n "$RG" -l "$LOCATION" --tags "${TAGS[@]}" -o none
az network vnet create -g "$RG" -n vnet-cao --address-prefix 10.10.0.0/16 \
  --subnet-name snet-app --subnet-prefix 10.10.1.0/24 --tags "${TAGS[@]}" -o none

for vm in web1 db1; do
  echo "==> VM $vm (2 to 3 minutes)"
  az vm create -g "$RG" -n "$vm" --image Ubuntu2404 --size "$SIZE" \
    --vnet-name vnet-cao --subnet snet-app \
    --admin-username azureuser --ssh-key-values "$KEY.pub" \
    --public-ip-sku Standard --tags "${TAGS[@]}" -o none
done
az vm open-port -g "$RG" -n web1 --port 80 --priority 1010 -o none

ip() { az vm show -d -g "$RG" -n "$1" --query "$2" -o tsv; }
cat > inventory/generated.ini <<INI
# Generated by targets/azure-up.sh. Copy these lines into inventory/hosts.ini.
# internal_address: the private IP the other server uses to reach this one
web1 ansible_host=$(ip web1 publicIps) internal_address=$(ip web1 privateIps) wordpress_site_url=http://$(ip web1 publicIps)
db1 ansible_host=$(ip db1 publicIps) internal_address=$(ip db1 privateIps)
INI
cat inventory/generated.ini
echo "==> Done."
