#!/usr/bin/env bash
# Workshop 1 (no-Azure path): start two local "servers" as containers on a
# private Docker network, like two VMs in one Azure virtual network.
#
#   web1: SSH on localhost:2221, HTTP on localhost:8081
#   db1 : SSH on localhost:2222, MariaDB reachable from web1 only (no published port)
#
# Writes inventory/generated.ini with the connection details.
# Safe to re-run: existing containers are replaced.
set -euo pipefail
cd "$(dirname "$0")/.."

KEY="${KEY:-$HOME/.ssh/cao_lab}"
NET="cao-net"
[[ -f "$KEY" ]] || ssh-keygen -q -t ed25519 -N "" -f "$KEY" -C "cao-lab"

echo "==> Building the node image"
docker build -q -t cao-node --build-arg PUBKEY="$(cat "$KEY.pub")" targets/node >/dev/null
docker network inspect "$NET" >/dev/null 2>&1 || docker network create "$NET" >/dev/null

docker rm -f web1 db1 >/dev/null 2>&1 || true
docker run -d --name web1 --hostname web1 --network "$NET" -p 2221:22 -p 8081:80 cao-node >/dev/null
docker run -d --name db1  --hostname db1  --network "$NET" -p 2222:22 cao-node >/dev/null
echo "    web1 started (ssh localhost:2221, http localhost:8081)"
echo "    db1  started (ssh localhost:2222)"

cat > inventory/generated.ini <<INI
# Generated by targets/local-up.sh. Copy these lines into inventory/hosts.ini.
# internal_address: how the other server reaches this one (here: Docker DNS name)
web1 ansible_host=127.0.0.1 ansible_port=2221 internal_address=web1 wordpress_site_url=http://localhost:8081
db1 ansible_host=127.0.0.1 ansible_port=2222 internal_address=db1
INI

echo "==> Done. Connection details are in inventory/generated.ini"
